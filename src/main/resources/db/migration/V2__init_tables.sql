CREATE TABLE bank.accounts
(
    deleted_at  TIMESTAMP,
    id          NUMBER(38, 0) NOT NULL,
    card_number VARCHAR2(255) NOT NULL,
    currency    VARCHAR2(255) NOT NULL,
    balance     DECIMAL   NOT NULL,
    customer_id NUMBER(38, 0) NOT NULL,
    status      VARCHAR2(255) NOT NULL,
    created_at  TIMESTAMP,
    due_to      TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP,
    CONSTRAINT pk_accounts PRIMARY KEY (id)
);

CREATE TABLE bank.activation_tokens
(
    id                    NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id               NUMBER(38, 0)                                  NOT NULL,
    activation_token_hash VARCHAR2(255)                                  NOT NULL,
    expires_at            TIMESTAMP NOT NULL,
    CONSTRAINT pk_activation_tokens PRIMARY KEY (id)
);

CREATE TABLE bank.address_infos
(
    id          NUMBER(38, 0) NOT NULL,
    country     VARCHAR2(255) NOT NULL,
    region      VARCHAR2(255) NOT NULL,
    city        VARCHAR2(255) NOT NULL,
    address     VARCHAR2(255) NOT NULL,
    postal_code VARCHAR2(255) NOT NULL,
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    version     NUMBER(38, 0),
    CONSTRAINT pk_address_infos PRIMARY KEY (id)
);

CREATE TABLE bank.customers
(
    deleted_at       TIMESTAMP,
    id               NUMBER(38, 0) NOT NULL,
    identity_user_id NUMBER(38, 0) NOT NULL,
    first_name       VARCHAR2(255) NOT NULL,
    last_name        VARCHAR2(255) NOT NULL,
    middle_name      VARCHAR2(255) NOT NULL,
    gender           VARCHAR2(255) NOT NULL,
    address_info_id  NUMBER(38, 0),
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP,
    version          NUMBER(38, 0),
    CONSTRAINT pk_customers PRIMARY KEY (id)
);

CREATE TABLE bank.employees
(
    id               NUMBER(38, 0) NOT NULL,
    identity_user_id NUMBER(38, 0) NOT NULL,
