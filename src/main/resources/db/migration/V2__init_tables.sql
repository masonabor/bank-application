CREATE TABLE bank.identity_users
(
    deleted_at               TIMESTAMP,
    id                       NUMBER(38, 0) NOT NULL,
    email                    VARCHAR2(255) NOT NULL,
    password_hash            VARCHAR2(255) NOT NULL,
    phone_number             VARCHAR2(255) NOT NULL,
    alternative_phone_number VARCHAR2(255),
    role                     VARCHAR2(255) NOT NULL,
    status                   NUMBER(5)     NOT NULL,
    created_at               TIMESTAMP,
    updated_at               TIMESTAMP,
    version                  NUMBER(38, 0),
    CONSTRAINT pk_identity_users PRIMARY KEY (id)
);

CREATE TABLE bank.postings
(
    deleted_at  TIMESTAMP,
    id          NUMBER(38, 0) NOT NULL,
    account_id  NUMBER(38, 0) NOT NULL,
    type        VARCHAR2(255),
    amount      DECIMAL,
    description VARCHAR2(255),
    transfer_id NUMBER(38, 0) NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT pk_postings PRIMARY KEY (id)
);

CREATE TABLE bank.refresh_tokens
(
    id                 NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id            NUMBER(38, 0)                                  NOT NULL,
    refresh_token_hash VARCHAR2(255)                                  NOT NULL,
    expires_at         TIMESTAMP NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id)
);

CREATE TABLE bank.transfers
(
    deleted_at          TIMESTAMP,
    id                  NUMBER(38, 0) NOT NULL,
    from_number         VARCHAR2(255) NOT NULL,
    to_number           VARCHAR2(255) NOT NULL,
    currency            VARCHAR2(255) NOT NULL,
    amount              DECIMAL NOT NULL,
    transaction_status  VARCHAR2(255) NOT NULL,
    transaction_comment VARCHAR2(255),
    created_at          TIMESTAMP,
    CONSTRAINT pk_transfers PRIMARY KEY (id)
);

